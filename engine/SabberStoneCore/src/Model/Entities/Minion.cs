        internal void UpdateAttackReadinessAfterKeywordLoss()
        {
            if (Zone != Controller.BoardZone) return;

            if (NumAttacksThisTurn >= Actions.CombatRules.AttackLimit(this))
                IsExhausted = true;

            if (HasCharge)
            {
                if (AttackableByRush)
                {
                    AttackableByRush = false;
                    Game.RushMinions.Remove(Id);
                }
                return;
            }
            if (BoardEntryTurn != Game.Turn || Controller != Game.CurrentPlayer) return;

            if (IsRush)
            {
                if (!AttackableByRush)
                {
                    AttackableByRush = true;
                    Game.RushMinions.Add(Id);
                }
            }
            else
            {
                if (AttackableByRush)
                {
                    AttackableByRush = false;
                    Game.RushMinions.Remove(Id);
                }
                IsExhausted = true;
            }
        }

