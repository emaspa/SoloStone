        public override void Destroy()
        {
            // A queued effect can outlive consumption or a previous death.
            if (Zone?.Type == Enums.Zone.SETASIDE || Zone?.Type == Enums.Zone.GRAVEYARD) return;
            Actions.DeathContextRules.Destroying(this);
            base.Destroy();
        }

        internal bool RestoresRebornState => !IsSilenced && Card.Id == "CAP_800"
            || AppliedEnchantments?.Exists(e => e.Card.Id == "CAP_800e") == true;

		/// <summary>Disables all special effects on this minion.
		/// It's not possible to undo a silence!
		/// </summary>
		public void Silence()
		{
			if (IsDormant) return;
            if (OngoingEffect is SabberStoneCore.Auras.EnrageEffect enrage) { enrage.Remove(); enrage.Update(); }
            Actions.PayloadRules.Clear(this, Actions.PayloadPolicy.Silence);
			if (Actions.HeraldRules.IsSoldier(Card))
            {
                this[GameTag.TAG_SCRIPT_DATA_NUM_1] = 0;
                this[Actions.HeraldRules.RealizedFactor] = 0;
            }
            // remove keywords
			HasTaunt = false;
			IsFrozen = false;
			IsEnraged = false;
			HasCharge = false;
            IsRush = false;
            CantAttackHeroes = false;
			HasWindfury = false;
            if (this[GameTag.MEGA_WINDFURY] > 0) this[GameTag.MEGA_WINDFURY] = 0;
            if (this[GameTag.IMMUNE_WHILE_ATTACKING] > 0) this[GameTag.IMMUNE_WHILE_ATTACKING] = 0;
            if (this[Actions.CombatRules.Tag4128] > 0) this[Actions.CombatRules.Tag4128] = 0;
			HasDivineShield = false;
			HasStealth = false;
			HasDeathrattle = false;
			HasBattleCry = false;
			HasInspire = false;
			HasLifeSteal = false;
			Poisonous = false;
			this[GameTag.REBORN] = 0;
			//CantBeTargetedByHeroPowers = false;
			CantBeTargetedBySpells = false;
			IsImmune = false;
			if (!IsRush || HasCharge)
            {
                AttackableByRush = false;
                Game.RushMinions.Remove(Id);
            }

			this[GameTag.SPELLPOWER] = 0;

			// remove enchantments, aura and trigger
			OngoingEffect?.Remove();
			Game.OneTurnEffects.RemoveAll(p => p.entityId == Id);
			ActivatedTrigger?.Remove();
			//Controller.BoardZone.Auras.ForEach(aura => aura.EntityRemoved(this));

			if (AppliedEnchantments != null)
				for (int i = AppliedEnchantments.Count - 1; i >= 0; i--)
				{
					if (AppliedEnchantments[i].Creator.Power?.Aura != null)
						continue;
					AppliedEnchantments[i].Remove();
				}

			// reset ATK and Health
			AttackDamage = Card.ATK;

			int cardBaseHealth = Card.Health;
			if (Damage > 0 && (AuraEffects?.Health ?? 0) != 0)
			{
				// Only removed local Health reduces damage; external aura Health survives Silence.
				int removedHealth = BaseHealth - AuraEffects.Health - cardBaseHealth;
				if (removedHealth > 0)
					Damage -= removedHealth;
				BaseHealth = cardBaseHealth;
				if (Damage >= BaseHealth) ToBeDestroyed = true;
			}
			else if (Health > cardBaseHealth)
				Health = cardBaseHealth;
			else
			{
				int delta = BaseHealth - cardBaseHealth;
				if (delta > 0)
					Damage -= delta;
				BaseHealth = cardBaseHealth;
			}

			if (_data.TryGetValue(GameTag.CONTROLLER_CHANGED_THIS_TURN, out int v) && v > 0)
			{
				Game.TaskQueue.Execute(new ControlTask(EntityType.SOURCE, true), Controller, this, null);
				this[GameTag.CONTROLLER_CHANGED_THIS_TURN] = 0;
			}

			if (_history && Card[GameTag.TRIGGER_VISUAL] == 1) this[GameTag.TRIGGER_VISUAL] = 0;

			IsSilenced = true;
            if (Actions.OldGodRules.Catalog(Card.Id).Length != 0) UpdateAttackReadinessAfterKeywordLoss();
            Actions.ColossalRules.StopRefill(this);

			Game.Log(LogLevel.INFO, BlockType.PLAY, "Minion", !Game.Logging? "":$"{this} got silenced!");
		}

        public override void Reset()
        {
            this[GameTag.NUM_TURNS_IN_PLAY] = 0;
            bool exhausted = IsExhausted;
            NativeTags.Remove(Actions.LifecycleRules.RecruitAppliedPlayer1);
            NativeTags.Remove(Actions.LifecycleRules.RecruitAppliedPlayer2);
            if (OngoingEffect is SabberStoneCore.Auras.EnrageEffect enrage) { enrage.Remove(); enrage.Update(); }
            if (Actions.BonusEffects.HasState(this)) _modifiedCantBeTargetedBySpells = null;
            bool resetCost = Actions.CostRules.RemoveNumericEnchantments(this) || Card.Id == "JAIL_453";
            // shortcut: retain legacy stat-only attachments for frozen replays; purge when movement policy is versioned.
            if (AppliedEnchantments != null)
                for (int i = AppliedEnchantments.Count - 1; i >= 0; i--)
                    if (AppliedEnchantments[i].Power?.Trigger != null || Actions.BonusEffects.RetainActor(AppliedEnchantments[i].Card)
                        || AppliedEnchantments[i][Actions.DiscoverRealRules.BoundEntity] != 0
                        || (AppliedEnchantments[i].Card.Id is "CATA_487e" or "CATA_487e1" or "MEND_044e4" or "TIME_024e" or "MEND_801e2" or "EDR_780e1"))
                        AppliedEnchantments[i].Remove();
            base.Reset();
            ClearHistoryDeathCause();
            if (resetCost) ResetCost();
            if (Card[GameTag.DORMANT] > 0) _data[GameTag.DORMANT] = 0;
			_modifiedATK = Card.ATK;
			_modifiedHealth = Card.Health;
			_damage = 0;
            _exhausted = false;
            if (_history && exhausted)
                Game.PowerHistory.Add(SabberStoneCore.Kettle.PowerHistoryBuilder.TagChange(Id, GameTag.EXHAUSTED, 0));
            _numAttackThisTurn = 0;
			_modifiedImmune = false;
			_modifiedTaunt = null;
			_modifiedStealth = Card.Stealth;

			OngoingEffect?.Remove();
			Game.OneTurnEffects.RemoveAll(p => p.entityId == Id);
			if (ToBeDestroyed)
			{
				//Game.DeadMinions.Remove(OrderOfPlay);
				Game.DeadMinions.Remove(this);
				ToBeDestroyed = false;
			}
		}

		/// <summary>
		/// Gets the Minions adjacent to this Minion in order from left to right.
		/// </summary>
		/// <param name="includeUntouchables">true if the result should contain Untouchable entities.</param>
		public Minion[] GetAdjacentMinions(bool includeUntouchables = false)
		{
			int pos = ZonePosition;
			if (!(Zone is BoardZone zone))
				throw new MethodAccessException();

			if (zone.HasLocations)
            {
                var neighbours = new List<Minion>(2);
                if (pos > 0 && zone.GetSlot(pos - 1) is Minion left && (includeUntouchables || !left.Untouchable)) neighbours.Add(left);
                if (pos + 1 < zone.SlotCount && zone.GetSlot(pos + 1) is Minion right && (includeUntouchables || !right.Untouchable)) neighbours.Add(right);
                return neighbours.ToArray();
            }
            if (includeUntouchables)
			{
				if (pos > 0)
				{
					if (pos < zone.Count - 1)
					{
						var arr = new Minion[2];
						arr[0] = zone[pos - 1];
						arr[1] = zone[pos + 1];
						return arr;
					}
					return new[] { zone[pos - 1] };
				}
				return pos < zone.Count - 1 ?
					new[] { zone[pos + 1] } :
					new Minion[0];
			}


			if (pos > 0)
			{
				Minion left;
				if (pos < zone.Count - 1)
				{
					left = zone[pos - 1];
					Minion right = zone[pos + 1];
					return left.Untouchable
						? (right.Untouchable ? new Minion[0] : new[] {right})
						: (right.Untouchable ? new[] {left} : new[] {left, right});
				}

				left = zone[pos - 1];
				return left.Untouchable ? new Minion[0] : new [] {left};
			}

			if (pos < zone.Count - 1)
			{
				Minion r = zone[pos + 1];
				return r.Untouchable ? new Minion[0] : new[] {r};
			}

			return new Minion[0];
		}

		/// <summary>
		/// Gets a value indicating whether this entity is playable by the player. Some entities require specific
		/// requirements before they can be played. This method will process the requirements and produce
		/// a result for the current state of the game.
		/// </summary>
		/// <value><c>true</c> if this entity is playable; otherwise, <c>false</c>.</value>
		public override bool IsPlayableByPlayer
		{
			get
			{
				// check if we got a slot on board for minions
				if (Controller.BoardZone.IsFull && (!Actions.EitherSideRules.Supports(Card) || Controller.Opponent.BoardZone.IsFull))
				{
					Game.Log(LogLevel.VERBOSE, BlockType.PLAY, "Playable",
						!Game.Logging? "":$"{this} isn't playable, because not enough place on board.");
					return false;
				}

				return base.IsPlayableByPlayer;
			}
		}

		public override IPlayable Clone(in Controller controller)
