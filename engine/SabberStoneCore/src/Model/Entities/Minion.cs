        internal void ClearNativeKeywords()
        {
            foreach (var tag in new[] { GameTag.DIVINE_SHIELD, GameTag.TAUNT, GameTag.STEALTH,
                GameTag.CHARGE, GameTag.WINDFURY, GameTag.POISONOUS, GameTag.LIFESTEAL,
                GameTag.RUSH, GameTag.REBORN, GameTag.CANT_BE_TARGETED_BY_SPELLS })
            {
                int before = this[tag];
                if (_data.Remove(tag) && _history && this[tag] != before)
                    Game.PowerHistory.Add(SabberStoneCore.Kettle.PowerHistoryBuilder.TagChange(Id, tag, this[tag]));
            }

        }

		internal void ResetAttributes()
		{
            Actions.DeathContextRules.ClearTransient(this);
            NativeTags.Remove(Actions.LifecycleRules.RecruitAppliedPlayer1);
            NativeTags.Remove(Actions.LifecycleRules.RecruitAppliedPlayer2);

			_numAttackThisTurn = 0;
			_damage = 0;
			_modifiedATK = null;
			_modifiedHealth = null;
            Actions.CostRules.ResetOverlay(this);
            Actions.CostRules.ClearScalarAuraMemory(this);
			_costManager?.ResetEnchantments();
			_modifiedCost = null;
			_modifiedStealth = null;
			_modifiedTaunt = null;
			_modifiedCantBeTargetedBySpells = null;
		}
