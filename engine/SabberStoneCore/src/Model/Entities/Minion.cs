        internal int? CopiedDormantState;

        internal void StartDormant()
        {
            if (Card.Id != "CORE_BT_156" && Card.Id != "EDR_469") return;
            bool copied = CopiedDormantState.HasValue;
            int dormant = CopiedDormantState ?? 1;
            CopiedDormantState = null;
            this[GameTag.DORMANT] = dormant;
            this[GameTag.DORMANT_VISUAL] = dormant;
            this[GameTag.UNTOUCHABLE] = dormant;
            if (!copied) this[GameTag.TAG_SCRIPT_DATA_NUM_1] = Card.Id == "CORE_BT_156" ? 2 : 0;
        }

        internal void LeaveDormant()
        {
            if (!IsDormant) return;
            this[GameTag.DORMANT] = 0;
            this[GameTag.DORMANT_VISUAL] = 0;
            this[GameTag.UNTOUCHABLE] = 0;
            this[GameTag.TAG_SCRIPT_DATA_NUM_1] = 0;
            AttackableByRush = false;
            RemoveDormantCondition();
        }

        internal void EnsureDormantCondition()
        {
            if (!IsDormant || Card.Id != "EDR_469") return;
            if (AppliedEnchantments != null)
                foreach (Enchantment condition in AppliedEnchantments)
                    if (condition.Card.Id == "EDR_469e") return;
            Card card = Cards.FromId("EDR_469e");
            Enchantment helper = Enchantment.GetInstance(Controller, this, this, card);
            card.Power.Trigger.Activate(helper);
        }

        internal void RemoveDormantCondition()
        {
            if (AppliedEnchantments == null) return;
            for (int i = AppliedEnchantments.Count - 1; i >= 0; i--)
                if (AppliedEnchantments[i].Card.Id == "EDR_469e") AppliedEnchantments[i].Remove();
        }

        internal void TickDormant()
        {
            if (!IsDormant || this[GameTag.TAG_SCRIPT_DATA_NUM_1] <= 0) return;
            if (--this[GameTag.TAG_SCRIPT_DATA_NUM_1] == 0) Awaken();
        }

        internal void Awaken()
        {
            if (!IsDormant || Zone != Controller.BoardZone) return;
            if (Game.History)
                Game.PowerHistory.Add(Kettle.PowerHistoryBuilder.BlockStart(BlockType.TRIGGER, Id, Card.Id, 0, 0));
            this[GameTag.DORMANT] = 0;
            this[GameTag.DORMANT_VISUAL] = 0;
            this[GameTag.UNTOUCHABLE] = 0;
            this[GameTag.DORMANT_AWAKENED_THIS_TURN] = 1;
            RemoveDormantCondition();
            IsExhausted = !HasCharge;
            BoardZone.InitialiseMinion(this);
            if (IsRush || HasCharge) IsExhausted = false;
            BoardZone.ActivateAura(this);
            foreach (var aura in Controller.BoardZone.Auras) aura.EntityAdded(this);
            foreach (var aura in Controller.BoardZone.AdjacentAuras) aura.BoardChanged = true;
            Game.Facts.Awakened(this,this);
            if (Game.History) Game.PowerHistory.Add(Kettle.PowerHistoryBuilder.BlockEnd());
        }

